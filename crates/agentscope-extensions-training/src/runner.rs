/// Controls the training lifecycle, mirroring `TrainingRunner`.
pub struct TrainingRunner {
    config: TrainingConfig,
    trinity_client: TrinityClient,
    router: Arc<TrainingRouter>,
    running: AtomicBool,
    commit_task: Mutex<Option<tokio::task::JoinHandle<()>>>,
    /// Hooks installed through [`TrainingRunner::attach`], weakly held so the runner
    /// never keeps an agent's middleware alive. [`TrainingRunner::stop`] disables them
    /// (Java `removeSystemHook`).
    hooks: Mutex<Vec<Weak<TrainingHook>>>,
}

impl TrainingRunner {
    /// Returns a new builder.
    pub fn builder() -> TrainingRunnerBuilder {
        TrainingRunnerBuilder::default()
    }

    /// The runner config.
    pub fn get_config(&self) -> &TrainingConfig {
        &self.config
    }

    /// Whether the runner is currently active.
    pub fn is_running(&self) -> bool {
        self.running.load(Ordering::SeqCst)
    }

    /// The underlying router.
    pub fn router(&self) -> Arc<TrainingRouter> {
        Arc::clone(&self.router)
    }

    /// Installs a [`TrainingHook`] on `chain` and returns it.
    ///
    /// This is the explicit-assembly counterpart of Java's global
    /// `AgentBase.addSystemHook(router)`: build the agent with the augmented chain,
    /// then call [`TrainingHook::bind_agent`] with the finished agent. See
    /// [`TrainingHook`] for the full pattern and the differences from Java.
    pub fn attach(&self, chain: &mut MiddlewareChain) -> Arc<TrainingHook> {
        let hook = Arc::new(TrainingHook::new(self.router()));
        hook.install(chain);
        self.hooks.lock().unwrap().push(Arc::downgrade(&hook));
        hook
    }

    /// Wires this runner into a [`HarnessAgentBuilder`]: installs a [`TrainingHook`] in the
    /// builder's middleware chain and binds it to the finished agent at build time.
    ///
    /// This is the one-call replacement for the manual assembly described on
    /// [`TrainingHook`] ("build the chain, build the agent, remember to bind" — the step
    /// TRAIN-03 shows is easy to forget): the hook enters the chain **before** `build()`, and
    /// the `on_agent_built` callback builds the [`ShadowAgentBlueprint`] from the
    /// [`HarnessAgentHandle`] and binds it. When `build()` returns, training is armed.
    ///
    /// Returns the builder together with the hook, so the caller can drive/inspect it
    /// ([`TrainingHook::has_agent`], [`TrainingHook::disable`], [`TrainingHook::blueprint`]);
    /// the runner itself only keeps a weak reference.
    ///
    /// **The builder's middleware chain is replaced** — `HarnessAgentBuilder::middleware`
    /// swaps the whole chain and the builder exposes no way to read it back, so a host that
    /// already owns a chain must keep using [`Self::attach`] (`attach(&mut chain)` then
    /// `builder.middleware(chain)`). Likewise `on_agent_built` holds a single callback: use
    /// [`Self::attach_to_with`] to keep your own.
    pub fn attach_to(
        &self,
        builder: HarnessAgentBuilder,
    ) -> (HarnessAgentBuilder, Arc<TrainingHook>) {
        self.attach_to_inner(builder, None)
    }

    /// [`Self::attach_to`] that preserves an existing `on_agent_built` callback.
    ///
    /// `HarnessAgentBuilder::on_agent_built` stores one callback, so registering a second one
    /// silently drops the first. `existing` runs first (the host keeps its observer), then the
    /// hook is bound.
    pub fn attach_to_with(
        &self,
        builder: HarnessAgentBuilder,
        existing: AgentBuiltCallback,
    ) -> (HarnessAgentBuilder, Arc<TrainingHook>) {
        self.attach_to_inner(builder, Some(existing))
    }

    fn attach_to_inner(
        &self,
        builder: HarnessAgentBuilder,
        existing: Option<AgentBuiltCallback>,
    ) -> (HarnessAgentBuilder, Arc<TrainingHook>) {
        let mut chain = MiddlewareChain::new();
        let hook = self.attach(&mut chain);
        let bind = Arc::clone(&hook);
        let builder =
            builder
                .middleware(chain)
                .on_agent_built(move |handle: &HarnessAgentHandle| {
                    if let Some(existing) = existing.as_ref() {
                        existing(handle);
                    }
                    bind.bind_blueprint(ShadowAgentBlueprint::from_handle(handle));
                });
        (builder, hook)
    }

    /// Disables every hook installed through [`Self::attach`].
    ///
    /// This is the Rust counterpart of Java `AgentBase.removeSystemHook(router)`: a
    /// built [`MiddlewareChain`] is immutable, so the hook stays in the chain but
    /// behaves like a plain passthrough. Entries whose hook has been dropped are
    /// pruned. Called automatically by [`Self::stop`].
    pub fn disable_attached_hooks(&self) {
        let mut hooks = self.hooks.lock().unwrap();
        hooks.retain(|weak| match weak.upgrade() {
            Some(hook) => {
                hook.disable();
                true
            }
            None => false,
        });
    }

    /// Number of live hooks installed through [`Self::attach`].
    pub fn attached_hook_count(&self) -> usize {
        let mut hooks = self.hooks.lock().unwrap();
        hooks.retain(|weak| weak.strong_count() > 0);
        hooks.len()
    }

    /// Number of attached hooks that were never bound to a production agent.
    ///
    /// An unbound hook is a silent passthrough: agent calls succeed but nothing is
    /// collected (Java has no binding step at all, so this can only be a wiring mistake).
    /// [`Self::start`] warns when this is non-zero; the count is exposed so a host can
    /// assert on the wiring instead of discovering it from missing training data.
    pub fn unbound_hook_count(&self) -> usize {
        let mut hooks = self.hooks.lock().unwrap();
        hooks.retain(|weak| weak.strong_count() > 0);
        hooks
            .iter()
            .filter_map(Weak::upgrade)
            .filter(|hook| !hook.has_agent())
            .count()
    }

    /// Whether a periodic-commit task is currently installed.
    pub fn has_commit_scheduler(&self) -> bool {
        self.commit_task.lock().unwrap().is_some()
    }

    /// Starts the runner (idempotent) and any periodic-commit task.
    pub fn start(&self) {
        if self.running.swap(true, Ordering::SeqCst) {
            tracing::warn!("TrainingRunner already running");
            return;
        }
        // `attach()` alone trains nothing until a hook is bound to an agent. Java has no
        // such step (the hook is global), so this is a Rust-only wiring mistake and must
        // not pass silently.
        let unbound = self.unbound_hook_count();
        if unbound > 0 {
            tracing::warn!(
                "{unbound} training hook(s) attached but not bound to an agent: their calls will not be trained (call TrainingHook::bind_agent / bind_blueprint)"
            );
        }
        self.start_commit_scheduler();
        tracing::info!("TrainingRunner started successfully");
    }

    /// Stops the runner (idempotent), performs a final commit and aborts the
    /// periodic-commit task.
    pub async fn stop(&self) {
        if !self.running.swap(false, Ordering::SeqCst) {
            tracing::warn!("TrainingRunner not running");
            return;
        }
        if let Some(handle) = self.commit_task.lock().unwrap().take() {
            handle.abort();
        }
        // Java `stop()` also removes the system hook; here that means disabling it.
        self.disable_attached_hooks();
        let _ = self.commit().await;
        tracing::info!("TrainingRunner stopped");
    }

    /// Triggers a commit, mirroring `commit`.
    pub async fn commit(&self) -> Result<()> {
        match self
            .trinity_client
            .commit(&CommitRequest::builder().build())
            .await
        {
            Ok(()) => {
                tracing::info!("Training commit successful");
                Ok(())
            }
            Err(e) => {
                tracing::error!("Failed to commit training: {e}");
                Err(e)
            }
        }
    }

    fn start_commit_scheduler(&self) {
        let interval = self.config.commit_interval_seconds();
        // Java parity: `TrainingRunner.startCommitScheduler()` only checks the
        // interval. `enableAutoCommit` is a dead knob in Java (written by the config,
        // never read), so Rust deliberately does not gate the scheduler on it either.
        if interval <= 0 {
            tracing::info!("Commit scheduler disabled (interval <= 0)");
            return;
        }
        let client = self.trinity_client.clone();
        let handle = tokio::spawn(async move {
            let mut ticker = tokio::time::interval(Duration::from_secs(interval as u64));
            // The first tick completes immediately; skip it so the first commit
            // happens after one full interval, matching the Java scheduler.
            ticker.tick().await;
            loop {
                ticker.tick().await;
                if let Err(e) = client.commit(&CommitRequest::builder().build()).await {
                    tracing::error!("Error in scheduled commit: {e}");
                }
            }
        });
        *self.commit_task.lock().unwrap() = Some(handle);
        tracing::info!("Commit scheduler started with interval: {interval} seconds");
    }
}

/// Builder for [`TrainingRunner`], mirroring `TrainingRunner.Builder`.
#[derive(Default)]
pub struct TrainingRunnerBuilder {
    config: Option<TrainingConfig>,
    config_builder: Option<TrainingConfigBuilder>,
}

impl TrainingRunnerBuilder {
    /// Sets a ready-made config (mutually exclusive with the incremental setters).
    pub fn config(mut self, config: TrainingConfig) -> Self {
        self.config = Some(config);
        self
    }

    fn config_builder(&mut self) -> Result<&mut TrainingConfigBuilder> {
        if self.config.is_some() {
            return Err(Error::Other(
                "Cannot use builder methods when config is already set".to_string(),
            ));
        }
        Ok(self
            .config_builder
            .get_or_insert_with(TrainingConfigBuilder::default))
    }

    pub fn trinity_endpoint(mut self, endpoint: impl Into<String>) -> Self {
        if let Ok(b) = self.config_builder() {
            b.trinity_endpoint = Some(endpoint.into());
        }
        self
    }
    pub fn model_name(mut self, model_name: impl Into<String>) -> Self {
        if let Ok(b) = self.config_builder() {
            b.model_name = model_name.into();
        }
        self
    }
    pub fn selection_strategy(mut self, strategy: Arc<dyn TrainingSelectionStrategy>) -> Self {
        if let Ok(b) = self.config_builder() {
            b.selection_strategy = Some(strategy);
        }
        self
    }
    pub fn reward_calculator(mut self, calculator: Arc<dyn RewardCalculator>) -> Self {
        if let Ok(b) = self.config_builder() {
            b.reward_calculator = Some(calculator);
        }
        self
    }
    pub fn commit_interval_seconds(mut self, seconds: i64) -> Self {
        if let Ok(b) = self.config_builder() {
            b.commit_interval_seconds = seconds;
        }
        self
    }
    pub fn repeat_time(mut self, repeat_time: i32) -> Self {
        if let Ok(b) = self.config_builder() {
            if repeat_time >= 1 {
                b.repeat_time = repeat_time;
            }
        }
        self
    }

    /// Builds the runner, requiring a config.
    pub fn build(self) -> Result<TrainingRunner> {
        let config = match self.config {
            Some(c) => c,
            None => self
                .config_builder
                .ok_or_else(|| {
                    Error::Other(
                        "TrainingConfig must be set. Use config() or builder methods.".to_string(),
                    )
                })?
                .build()?,
        };
        let trinity_client = TrinityClient::builder()
            .endpoint(config.trinity_endpoint())
            .timeout(config.http_timeout())
            .build()?;
        let router = Arc::new(TrainingRouter::new(config.clone(), trinity_client.clone()));
        Ok(TrainingRunner {
            config,
            trinity_client,
            router,
            running: AtomicBool::new(false),
            commit_task: Mutex::new(None),
            hooks: Mutex::new(Vec::new()),
        })
    }
}

fn now_millis() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_millis() as u64)
        .unwrap_or(0)
}


/// The outcome of running one shadow agent, exposed for observability/testing.
#[derive(Debug, Clone, PartialEq)]
pub struct ShadowRunReport {
    pub task_id: String,
    pub run_id: String,
    pub msg_id_count: usize,
    pub reward: Option<f64>,
    pub feedback_submitted: bool,
}

/// RAII guard for one admitted shadow run: releases the admission slot on drop.
struct ShadowAdmission<'a> {
    router: &'a TrainingRouter,
}

impl Drop for ShadowAdmission<'_> {
    fn drop(&mut self) {
        self.router.shadow_in_flight.fetch_sub(1, Ordering::SeqCst);
    }
}

/// Runs shadow agents to collect training data, mirroring `TrainingRouter`.
///
/// Java registers this as a global `PreCall`/`PostCall` hook. Rust has no global
/// hook registry, so the router is driven explicitly in two ways:
///
/// * directly, by handing it the production agent, the input messages and an
///   optional training annotation ([`TrainingRouter::decide`] /
///   [`TrainingRouter::run_shadow`]);
/// * automatically, through [`TrainingHook`], a middleware that observes the end of
///   a production call on the agents the host attaches it to.
pub struct TrainingRouter {
    config: TrainingConfig,
    trinity_client: TrinityClient,
    /// Caps how many shadow runs execute at once: the Rust counterpart of Java's
    /// `Schedulers.newBoundedElastic(shadowPoolSize, shadowPoolCapacity, ...)`.
    shadow_slots: Arc<tokio::sync::Semaphore>,
    /// Bounded admission (queue) counter, the counterpart of the queue bound of
    /// Java's bounded-elastic scheduler (`shadowPoolCapacity`).
    shadow_in_flight: AtomicUsize,
    /// Run-id allocator used by this router. Instance-scoped by default instead of
    /// process-global, so independent runners (and tests) cannot interfere.
    run_registry: Arc<RunRegistry>,
    /// Run-context store used by this router.
    task_registry: Arc<TaskExecutionRegistry>,
}

impl TrainingRouter {
    /// Creates a router from a config and a Trinity client.
    ///
    /// The router gets its **own** [`RunRegistry`] / [`TaskExecutionRegistry`]. Java
    /// keeps both in `static` fields, so all routers in a JVM share them; use
    /// [`TrainingRouter::with_global_registries`] to reproduce that exactly.
    pub fn new(config: TrainingConfig, trinity_client: TrinityClient) -> Self {
        Self::with_registries(
            config,
            trinity_client,
            Arc::new(RunRegistry::new()),
            Arc::new(TaskExecutionRegistry::new()),
        )
    }

    /// Creates a router sharing the process-wide registries (Java parity).
    pub fn with_global_registries(config: TrainingConfig, trinity_client: TrinityClient) -> Self {
        Self::with_registries(
            config,
            trinity_client,
            RunRegistry::global(),
            TaskExecutionRegistry::global(),
        )
    }

    /// Creates a router with explicit registries (dependency injection).
    pub fn with_registries(
        config: TrainingConfig,
        trinity_client: TrinityClient,
        run_registry: Arc<RunRegistry>,
        task_registry: Arc<TaskExecutionRegistry>,
    ) -> Self {
        // Java's `newBoundedElastic` requires a positive size; keeping at least one
        // slot means a zero config can never deadlock the router.
        let slots = config.shadow_pool_size().max(1);
        Self {
            config,
            trinity_client,
            shadow_slots: Arc::new(tokio::sync::Semaphore::new(slots)),
            shadow_in_flight: AtomicUsize::new(0),
            run_registry,
            task_registry,
        }
    }

    /// Number of shadow slots currently free (observability for hosts and tests).
    pub fn available_shadow_slots(&self) -> usize {
        self.shadow_slots.available_permits()
    }

    /// Number of shadow runs currently admitted (in flight or waiting for a slot).
    pub fn pending_shadow_runs(&self) -> usize {
        self.shadow_in_flight.load(Ordering::SeqCst)
    }

    /// The run-id allocator this router uses.
    pub fn run_registry(&self) -> &Arc<RunRegistry> {
        &self.run_registry
    }

    /// The run-context store this router uses.
    pub fn task_registry(&self) -> &Arc<TaskExecutionRegistry> {
        &self.task_registry
    }

    /// Admits one shadow run, returning `None` when the bounded queue is full.
    ///
    /// Java's `Schedulers.newBoundedElastic(size, capacity, ...)` rejects work once
    /// `capacity` tasks are queued; a tokio semaphore has an unbounded wait queue, so
    /// the bound is enforced here by counting admitted-but-unfinished runs. Training is
    /// best-effort data collection, so an over-capacity run is dropped (with a warning)
    /// rather than failing the production call. `capacity <= 0` is treated as `1` so a
    /// zero cannot wedge the router.
    fn try_admit_shadow_run(&self) -> Option<ShadowAdmission<'_>> {
        let capacity = self.config.shadow_pool_capacity().max(1);
        if self.shadow_in_flight.fetch_add(1, Ordering::SeqCst) >= capacity {
            self.shadow_in_flight.fetch_sub(1, Ordering::SeqCst);
            return None;
        }
        Some(ShadowAdmission { router: self })
    }

    /// The underlying config.
    pub fn config(&self) -> &TrainingConfig {
        &self.config
    }

    /// Makes a selection decision for a call, mirroring the branch of `handlePostCall`.
    pub fn decide(
        &self,
        agent_name: &str,
        inputs: &[Msg],
        output: &Msg,
        annotation: Option<&TrainingAnnotation>,
    ) -> SelectionDecision {
        // Prevent shadow agents from re-triggering training (recursion guard).
        if agent_name.contains("-shadow") {
            return SelectionDecision::reject("shadow-agent");
        }
        self.config
            .selection_strategy()
            .should_select(agent_name, inputs, output, annotation)
    }

    /// Runs the shadow training flow for a single selected call.
    ///
    /// Runs `repeat_time` iterations with the same task id and incrementing run
    /// ids. This is blocking (awaited) to remain testable; the automatic path
    /// ([`TrainingHook`]) spawns it instead, like Java's `subscribeOn(asyncScheduler)`.
    pub async fn run_shadow(
        &self,
        agent_name: &str,
        production_agent: &ReActAgent,
        inputs: Vec<Msg>,
        output: Msg,
        annotation: Option<&TrainingAnnotation>,
        spec: ShadowAgentSpec,
    ) -> Vec<ShadowRunReport> {
        let blueprint = ShadowAgentBlueprint::from_agent(production_agent);
        self.run_shadow_blueprint(agent_name, &blueprint, inputs, output, annotation, spec)
            .await
    }

    /// Runs the shadow flow from a [`ShadowAgentBlueprint`] snapshot.
    ///
    /// Same as [`Self::run_shadow`], but the production agent is described by a borrowed
    /// snapshot instead of an `Arc<ReActAgent>` — the path [`TrainingHook`] uses.
    pub async fn run_shadow_blueprint(
        &self,
        agent_name: &str,
        production: &ShadowAgentBlueprint,
        inputs: Vec<Msg>,
        output: Msg,
        annotation: Option<&TrainingAnnotation>,
        spec: ShadowAgentSpec,
    ) -> Vec<ShadowRunReport> {
        let mut reports = Vec::new();
        let decision = self.decide(agent_name, &inputs, &output, annotation);
        if !decision.should_train() {
            return reports;
        }

        let task_id = decision
            .metadata()
            .get("taskId")
            .and_then(|v| v.as_str())
            .map(str::to_string)
            .unwrap_or_else(task_id_generator::generate);

        let repeat = self.config.repeat_time();
        for _ in 0..repeat {
            // Bounded queue (Java `newBoundedElastic` capacity): drop the run instead
            // of queueing without bound when too many are already pending.
            let Some(_admission) = self.try_admit_shadow_run() else {
                tracing::warn!(
                    "Shadow pool queue full (capacity {}), skipping training run for task {}",
                    self.config.shadow_pool_capacity(),
                    task_id
                );
                break;
            };
            // Bounded shadow concurrency (Java `newBoundedElastic`); the permit is
            // released when this iteration finishes.
            let _slot = match Arc::clone(&self.shadow_slots).acquire_owned().await {
                Ok(slot) => slot,
                Err(e) => {
                    tracing::error!("Shadow pool unavailable, aborting training run: {e}");
                    break;
                }
            };
            let run_id = self.run_registry.allocate_run_id(&task_id);
            let context = Arc::new(RunExecutionContext::create(task_id.clone(), run_id.clone()));

            let report = self
                .run_single_shadow(production, inputs.clone(), context.clone(), spec.clone())
                .await;
            reports.push(report);
        }
        // TRAIN-05: the run counter is cleaned up once, after the loop, so an early exit
        // (queue bound reached / pool unavailable) cannot leak it either — Java cleans up
        // in `doFinally` of the last run, which a `break` skips.
        self.run_registry.cleanup(&task_id);
        reports
    }

    async fn run_single_shadow(
        &self,
        production_agent: &ShadowAgentBlueprint,
        inputs: Vec<Msg>,
        context: Arc<RunExecutionContext>,
        spec: ShadowAgentSpec,
    ) -> ShadowRunReport {
        let mut report = ShadowRunReport {
            task_id: context.get_task_id().to_string(),
            run_id: context.get_run_id().to_string(),
            msg_id_count: 0,
            reward: None,
            feedback_submitted: false,
        };

        // Build the Trinity-backed model adapter, pointing the shadow agent at the
        // configured training model (`{endpoint}/v1`), exactly like the Java router.
        let base_url = format!("{}/v1", self.trinity_client.endpoint());
        let adapter = match TrinityModelAdapter::builder()
            .base_url(base_url)
            .model_name(self.config.model_name())
            .api_key(self.config.trinity_api_key())
            .execution_context(context.clone())
            .build()
        {
            Ok(a) => Arc::new(a),
            Err(e) => {
                tracing::error!("Failed to create Trinity model adapter: {e}");
                return report;
            }
        };

        // Clone the production agent, replacing its model with the adapter.
        let shadow = match AgentCloner::clone_blueprint(production_agent, adapter, spec) {
            Ok(a) => a,
            Err(e) => {
                tracing::error!("Failed to clone shadow agent: {e}");
                return report;
            }
        };

        // Execute the shadow agent.
        match CallableAgent::call(&shadow, inputs).await {
            Ok(_msg) => {
                context.set_messages(shadow.agent_state().context().to_vec());
            }
            Err(e) => {
                tracing::error!("Shadow agent failed for {context}: {e}");
                return report;
            }
        }

        let msg_ids = context.get_msg_ids();
        report.msg_id_count = msg_ids.len();
        if msg_ids.is_empty() {
            tracing::warn!("No msg_ids collected for {context}");
            return report;
        }

        let reward = self.config.reward_calculator().calculate(&shadow);
        report.reward = Some(reward);

        let request = FeedbackRequest::builder()
            .task_id(context.get_task_id())
            .run_id(context.get_run_id())
            .msg_ids(msg_ids)
            .reward(reward)
            .build();

        match self.trinity_client.feedback(&request).await {
            Ok(()) => {
                report.feedback_submitted = true;
                self.task_registry.register(context);
            }
            Err(e) => tracing::error!("Failed to submit feedback: {e}"),
        }

        report
    }
}


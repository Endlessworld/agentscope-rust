/// Optional overrides for the fields [`AgentCloner`] copies onto a shadow agent.
///
/// Every field defaults to `None`, meaning "inherit from the production agent"
/// (`ReActAgent::sys_prompt()` / `ReActAgent::max_iters()`), which mirrors Java's
/// reflective field copy. Set a field only to deliberately diverge from the
/// production agent.
#[derive(Debug, Clone, Default)]
pub struct ShadowAgentSpec {
    /// Overrides the system prompt inherited from the production agent.
    pub sys_prompt: Option<String>,
    /// Overrides the max reasoning iterations inherited from the production agent.
    pub max_iters: Option<i32>,
}

/// Clones an agent with a replacement model, mirroring `AgentCloner`.
///
/// The Java version uses reflection to read private fields; Rust instead copies
/// the fields exposed through the [`agentscope_core::Agent`] trait (name,
/// description, toolkit) plus the `ReActAgent` getters for the system prompt and
/// max iterations, then rebuilds the agent with a fresh (empty) state.
///
/// Not migrated: Java's `modelExecutionConfig` / `toolExecutionConfig` /
/// `toolExecutionContext` have no counterpart on `ReActAgent` in Rust (core has
/// neither the fields nor builder setters); execution tuning is per call
/// (`GenerateOptions::execution_config`) or per tool (`ToolConfig`), so a cloned
/// agent simply uses the defaults for every call.
pub struct AgentCloner;

/// Snapshot of the production-agent fields a shadow clone needs.
///
/// Java's `AgentCloner` reads them off the live agent with reflection; Rust copies them
/// into this value. Taking a snapshot instead of holding a reference is what lets a
/// [`TrainingHook`] bind to an agent it only *borrows* — notably the `ReActAgent` owned by
/// a `HarnessAgent` (`HarnessAgent::agent()`), which is never handed
/// out as an `Arc`. Only `name` / `description` / `sys_prompt` / `max_iters` are copied.
/// The [`Toolkit`] is a clone, so it shares the tool table with the production toolkit
/// (tools registered after binding are still visible here); [`AgentCloner::clone_blueprint`]
/// copies that table for the shadow so it never registers into the production one.
#[derive(Clone)]
pub struct ShadowAgentBlueprint {
    name: String,
    description: String,
    sys_prompt: String,
    max_iters: i32,
    toolkit: Toolkit,
}

impl ShadowAgentBlueprint {
    /// Snapshots the fields copied from `agent` onto its shadow clone.
    pub fn from_agent(agent: &ReActAgent) -> Self {
        Self {
            name: agent.name().to_string(),
            description: agent.description().to_string(),
            sys_prompt: agent.sys_prompt().to_string(),
            max_iters: agent.max_iters(),
            toolkit: agent.toolkit().clone(),
        }
    }

    /// Snapshots the same fields off a built harness agent.
    ///
    /// [`HarnessAgentHandle`] is the only borrow a `HarnessAgentBuilder::on_agent_built`
    /// callback receives; its `description`/`sys_prompt`/`max_iters` getters read back the
    /// values the embedded `ReActAgent` really runs with (builder defaults applied), so a
    /// blueprint built here matches the production agent exactly.
    ///
    /// `agent_id` is intentionally not carried: the blueprint only holds what a shadow
    /// clone consumes, and nothing in the clone path reads an agent id — the clone is named
    /// `{name}-shadow` and the router accounts for runs by that name.
    pub fn from_handle(handle: &HarnessAgentHandle) -> Self {
        Self {
            name: handle.name().to_string(),
            description: handle.description().to_string(),
            sys_prompt: handle.sys_prompt().to_string(),
            // The handle reports the effective cap as `usize`; core takes `i32`.
            max_iters: handle.max_iters().min(i32::MAX as usize) as i32,
            toolkit: handle.toolkit().clone(),
        }
    }

    /// The production agent name (shadow clones get a `-shadow` suffix).
    pub fn name(&self) -> &str {
        &self.name
    }

    /// The production agent description, copied onto the clone.
    pub fn description(&self) -> &str {
        &self.description
    }

    /// The system prompt inherited by the clone (unless a [`ShadowAgentSpec`] overrides it).
    pub fn sys_prompt(&self) -> &str {
        &self.sys_prompt
    }

    /// The max reasoning iterations inherited by the clone.
    pub fn max_iters(&self) -> i32 {
        self.max_iters
    }

    /// The tool catalog shared with the clone.
    pub fn toolkit(&self) -> &Toolkit {
        &self.toolkit
    }
}

impl From<&ReActAgent> for ShadowAgentBlueprint {
    fn from(agent: &ReActAgent) -> Self {
        Self::from_agent(agent)
    }
}

impl std::fmt::Debug for ShadowAgentBlueprint {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("ShadowAgentBlueprint")
            .field("name", &self.name)
            .field("max_iters", &self.max_iters)
            .field("tools", &self.toolkit.tool_names().len())
            .finish()
    }
}

impl AgentCloner {
    /// Clones `original`, replacing its model with `new_model`.
    ///
    /// The clone gets a `-shadow` name suffix and a fresh, empty conversation
    /// state (no shared memory with the original).
    pub fn clone_with_model(
        original: &ReActAgent,
        new_model: Arc<dyn Model>,
        spec: ShadowAgentSpec,
    ) -> Result<ReActAgent> {
        Self::clone_blueprint(&ShadowAgentBlueprint::from_agent(original), new_model, spec)
    }

    /// Clones from a [`ShadowAgentBlueprint`] snapshot.
    ///
    /// Used by the automatic [`TrainingHook`] path, which may only borrow the production
    /// agent (a `HarnessAgent` owns its `ReActAgent`), instead of requiring an
    /// `Arc<ReActAgent>`.
    pub fn clone_blueprint(
        blueprint: &ShadowAgentBlueprint,
        new_model: Arc<dyn Model>,
        spec: ShadowAgentSpec,
    ) -> Result<ReActAgent> {
        // Java copies `sysPrompt` / `maxIters` reflectively; Rust carries them in the
        // blueprint and only lets `ShadowAgentSpec` override them.
        let sys_prompt = spec
            .sys_prompt
            .unwrap_or_else(|| blueprint.sys_prompt.clone());
        let max_iters = spec.max_iters.unwrap_or(blueprint.max_iters);
        // The blueprint's `Toolkit` clone shares the tool table (`Arc`), so handing it to
        // the clone would give the shadow the *production* tool instances — notably a
        // `todo_write` bound to the production `TaskContextState`. Take an independent
        // copy instead (same tool set, own table) and, when the production agent
        // registered `todo_write`, let the builder register its own instance so shadow
        // todos never write through to production state.
        let toolkit = blueprint.toolkit.copy();
        let todo_tool = blueprint.toolkit.get_tool("todo_write").is_some();
        let builder = ReActAgent::builder()
            .name(format!("{}-shadow", blueprint.name))
            .description(blueprint.description.clone())
            .model(new_model)
            .toolkit(toolkit)
            .sys_prompt(sys_prompt)
            .max_iters(max_iters)
            .todo_tool(todo_tool);
        builder.build().map_err(|e| {
            Error::Agent(format!("Failed to clone ReActAgent: {}", blueprint.name).into())
                .with_source_boxed(e)
        })
    }
}

// Small helper so we can attach a source error message without exposing internals.
trait ErrorExt {
    fn with_source_boxed(self, source: Error) -> Error;
}

impl ErrorExt for Error {
    fn with_source_boxed(self, source: Error) -> Error {
        Error::Other(format!("{self}: {source}"))
    }
}


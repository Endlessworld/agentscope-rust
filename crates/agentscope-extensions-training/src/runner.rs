    // --- TRAIN-05: an early exit must not leak the run counter -------------------

    #[tokio::test]
    async fn run_shadow_cleans_up_the_run_counter_after_an_early_exit() {
        /// Makes the bounded queue full from inside the first shadow run: `shadow_in_flight`
        /// is the bounded-elastic queue, so one counted-but-unfinished run (what a
        /// concurrent run looks like to this router) makes the next iteration's admission
        /// fail and `break` — *after* the first iteration allocated a run id.
        struct QueueSaturator {
            router: std::sync::Mutex<Weak<TrainingRouter>>,
            filled: AtomicBool,
        }
        impl RewardCalculator for QueueSaturator {
            fn calculate(&self, _agent: &ReActAgent) -> f64 {
                if !self.filled.swap(true, Ordering::SeqCst) {
                    if let Some(router) = self.router.lock().unwrap().upgrade() {
                        router.shadow_in_flight.fetch_add(1, Ordering::SeqCst);
                    }
                }
                0.0
            }
        }

        let (endpoint, served, server) = trinity_mock::spawn(2);
        let saturator = Arc::new(QueueSaturator {
            router: std::sync::Mutex::new(Weak::new()),
            filled: AtomicBool::new(false),
        });
        let reward: Arc<dyn RewardCalculator> = saturator.clone();
        let config = TrainingConfig::builder()
            .trinity_endpoint(&endpoint)
            .selection_strategy(Arc::new(crate::strategy::ExplicitMarkingStrategy::create()))
            .reward_calculator(reward)
            .shadow_pool_capacity(1)
            .repeat_time(2)
            .build()
            .unwrap();
        let client = TrinityClient::builder().endpoint(&endpoint).build().unwrap();
        let router = Arc::new(TrainingRouter::new(config, client));
        *saturator.router.lock().unwrap() = Arc::downgrade(&router);

        let annotation = TrainingAnnotation::builder()
            .enabled(true)
            .task_id("task-cleanup")
            .build();
        let prod = model_support::agent("prod");
        let reports = tokio::time::timeout(
            Duration::from_secs(10),
            router.run_shadow(
                "prod",
                &prod,
                vec![Msg::user("hi")],
                Msg::assistant("ok"),
                Some(&annotation),
                ShadowAgentSpec::default(),
            ),
        )
        .await
        .expect("a shadow round must not stall on the fake Trinity endpoint");
        assert_eq!(reports.len(), 1, "only the first iteration fits the bound");
        assert!(reports[0].feedback_submitted);
        // Before the fix the cleanup only ran on the last iteration, so an early `break`
        // left the counter in the registry for the life of the process.
        assert_eq!(router.run_registry().get_current_run_count("task-cleanup"), 0);
        assert_eq!(router.run_registry().size(), 0);
        assert_eq!(served.load(Ordering::SeqCst), 2);
        let _ = server.join().unwrap();
    }


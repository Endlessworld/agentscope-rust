    /// Drains an event stream to completion: the hook's post-call step sits at the tail
    /// of the stream, so it only runs once every item has been consumed.
    async fn drain(mut stream: EventStream) -> Vec<Result<AgentEvent>> {
        let mut events = Vec::new();
        while let Some(item) = stream.next().await {
            events.push(item);
        }
        events
    }

    /// Waits (bounded) until `ready` holds.
    ///
    /// The hook runs its post-call step on a spawned task (Java
    /// `subscribeOn(asyncScheduler)`), so its counters advance after the production call
    /// already returned; tests must observe them instead of assuming they are final.
    async fn wait_until(what: &str, mut ready: impl FnMut() -> bool) {
        for _ in 0..500 {
            if ready() {
                return;
            }
            tokio::time::sleep(Duration::from_millis(10)).await;
        }
        panic!("timed out waiting for {what}");
    }


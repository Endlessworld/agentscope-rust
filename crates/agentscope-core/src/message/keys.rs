/// Well-known message metadata keys, mirroring `MessageMetadataKeys` in the Java SDK.
pub mod metadata_keys {
    /// Marks a message so multiagent formatters keep it as a separate message instead of
    /// merging it into conversation history. Type: bool.
    pub const BYPASS_MULTIAGENT_HISTORY_MERGE: &str = "_bypass_multiagent_history_merge";

    /// Internal flag marking structured-output reminder messages. Type: bool.
    pub const STRUCTURED_OUTPUT_REMINDER: &str = "_structured_output_reminder";

    /// Stores the structured-output reminder mode (TOOL_CHOICE / PROMPT). Type: string.
    pub const STRUCTURED_OUTPUT_REMINDER_TYPE: &str = "_structured_output_reminder_type";

    /// Contains accumulated token usage information. Type: `ChatUsage`.
    pub const CHAT_USAGE: &str = "_chat_usage";

    /// Contains the structured response data generated by the generate_response tool.
    /// Type: `serde_json::Map` or a user-defined type.
    pub const STRUCTURED_OUTPUT: &str = "_structured_output";

    /// When true, the formatter adds `cache_control: {"type": "ephemeral"}` to this message.
    pub const CACHE_CONTROL: &str = "_cache_control";

    /// Metadata key for storing the generate reason. Type: `GenerateReason` name.
    pub const GENERATE_REASON: &str = "agentscope_generate_reason";

    /// Metadata key carrying `Vec<ConfirmResult>` when resuming a permission HITL pause.
    pub const CONFIRM_RESULTS: &str = "agentscope_confirm_results";

    /// Metadata key (bool) marking a message as synthetic (framework-injected).
    pub const SYNTHETIC: &str = "agentscope_synthetic";

    /// Metadata key (string) describing the kind of synthetic reminder, e.g. "todo_state".
    pub const REMINDER_KIND: &str = "agentscope_reminder_kind";
}

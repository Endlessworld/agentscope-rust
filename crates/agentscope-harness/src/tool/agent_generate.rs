//! `AgentGenerateTool` — creates a subagent declaration from a natural-language
//! description, mirroring `io.agentscope.harness.agent.tool.AgentGenerateTool`.
//!
//! Writes `subagents/<name>.md` with YAML front matter (`description`, optional
//! `tools`) and the generated system prompt as the body, so the standard
//! `subagents/` loader picks it up on the next session.
use std::sync::Arc;

use agentscope_core::agent::RuntimeContext;
use agentscope_core::error::Result;
use agentscope_core::message::{JsonMap, ToolResultBlock};
use agentscope_core::tool::{Tool, ToolExecutionContext};
use async_trait::async_trait;

use crate::filesystem::Filesystem;
use crate::tool::str_arg;

/// Directory that holds subagent declarations.
pub use crate::agent::subagent::SUBAGENTS_DIR;

/// Generates a subagent spec file from a natural-language description.
#[derive(Clone)]
pub struct AgentGenerateTool {
    fs: Arc<dyn Filesystem>,
    subagents_dir: String,
    /// When set, the spec is generated by the model
    /// ([`SubagentSpecGenerator`](crate::agent::SubagentSpecGenerator)) instead of the
    /// fixed template. A generation failure falls back to the template.
    model: Option<Arc<dyn agentscope_core::model::Model>>,
}

impl AgentGenerateTool {
    pub fn new(fs: Arc<dyn Filesystem>) -> Self {
        Self {
            fs,
            subagents_dir: SUBAGENTS_DIR.into(),
            model: None,
        }
    }

    /// Overrides the directory declarations are written to.
    pub fn with_subagents_dir(mut self, dir: impl Into<String>) -> Self {
        self.subagents_dir = dir.into();
        self
    }

    /// Generates the spec with `model` (Java `AgentGenerateTool(SubagentSpecGenerator, …)`).
    pub fn with_model(mut self, model: Arc<dyn agentscope_core::model::Model>) -> Self {
        self.model = Some(model);
        self
    }

    fn sanitize_name(name: &str) -> Option<String> {
        let cleaned: String = name
            .trim()
            .to_lowercase()
            .chars()
            .map(|c| {
                if c.is_ascii_alphanumeric() || c == '-' || c == '_' {
                    c
                } else {
                    '-'
                }
            })
            .collect();
        let cleaned = cleaned.trim_matches('-').to_string();
        if cleaned.is_empty() {
            None
        } else {
            Some(cleaned)
        }
    }

    fn render_spec(name: &str, description: &str, tools: Option<&str>) -> String {
        let mut fm = format!("---\nname: {name}\ndescription: {description}\n");
        if let Some(t) = tools {
            let t = t.trim();
            if !t.is_empty() {
                fm.push_str(&format!("tools: {t}\n"));
            }
        }
        fm.push_str("---\n\n");
        fm.push_str(&format!(
            "You are `{name}`, a focused subagent.\n\nMission:\n{description}\n\n\
             Work autonomously toward the mission, use only the tools you need, \
             and return a concise final answer.\n"
        ));
        fm
    }

    /// Registers the tool into a toolkit.
    pub fn register(toolkit: &agentscope_core::tool::Toolkit, fs: Arc<dyn Filesystem>) {
        toolkit.register_tool(Arc::new(Self::new(fs)));
    }
}

#[async_trait]
impl Tool for AgentGenerateTool {
    fn name(&self) -> &str {
        "agent_generate"
    }

    fn description(&self) -> &str {
        "Create a new subagent from a natural-language description. \
         Writes subagents/<name>.md which is loaded as a subagent declaration."
    }

    fn is_read_only(&self) -> bool {
        false
    }

    fn parameters_schema(&self) -> serde_json::Value {
        serde_json::json!({
            "type": "object",
            "properties": {
                "name": {"type": "string", "description": "Subagent name (letters, digits, '-', '_')"},
                "description": {"type": "string", "description": "What this subagent does, in one or two sentences"},
                "tools": {"type": "string", "description": "Optional comma-separated tool allow-list"}
            },
            "required": ["name", "description"]
        })
    }

    async fn call(&self, args: JsonMap, _ctx: ToolExecutionContext) -> Result<ToolResultBlock> {
        let raw_name = str_arg(&args, "name")?;
        let description = str_arg(&args, "description")?;
        let tools = args.get("tools").and_then(|v| v.as_str()).map(String::from);

        let Some(name) = Self::sanitize_name(&raw_name) else {
            return Ok(ToolResultBlock::error(format!(
                "Invalid subagent name: '{raw_name}'"
            )));
        };
        if description.trim().is_empty() {
            return Ok(ToolResultBlock::error("description must not be empty"));
        }

        let path = format!("{}/{name}.md", self.subagents_dir);
        let rt = RuntimeContext::default();
        if self.fs.exists(&rt, &path).await.unwrap_or(false) {
            return Ok(ToolResultBlock::error(format!(
                "Subagent already exists: {path}. Choose another name."
            )));
        }
        let content = match &self.model {
            Some(model) => {
                let generator = crate::agent::SubagentSpecGenerator::new(Arc::clone(model));
                match generator
                    .generate_and_validate(description.trim(), &name, &[], None)
                    .await
                {
                    Ok(spec) => spec.markdown,
                    Err(error) => {
                        tracing::warn!(
                            "agent_generate: model spec generation failed for '{name}', \
                             falling back to the template: {error}"
                        );
                        Self::render_spec(&name, description.trim(), tools.as_deref())
                    }
                }
            }
            None => Self::render_spec(&name, description.trim(), tools.as_deref()),
        };
        match self.fs.write(&rt, &path, &content).await {
            Ok(()) => Ok(ToolResultBlock::text(format!(
                "Created subagent '{name}' at {path}"
            ))),
            Err(e) => Ok(ToolResultBlock::error(e.to_string())),
        }
    }
}

#[cfg(test)]
mod tests {
    use std::sync::Arc;

    use agentscope_core::message::{ContentBlock, TextBlock};
    use agentscope_core::model::{ChatResponse, GenerateOptions, Model, ToolSchema};
    use futures::stream::{self, BoxStream};

    use super::*;
    use crate::filesystem::LocalFilesystem;

    struct StubModel {
        text: String,
    }

    impl Model for StubModel {
        fn stream(
            &self,
            _messages: Vec<agentscope_core::message::Msg>,
            _tools: Vec<ToolSchema>,
            _options: GenerateOptions,
        ) -> BoxStream<'_, crate::Result<ChatResponse>> {
            let item = ChatResponse::new(
                "r1",
                vec![ContentBlock::Text(TextBlock::new(self.text.clone()))],
                Default::default(),
                None,
                None,
            );
            Box::pin(stream::iter(vec![Ok(item)]))
        }

        fn model_name(&self) -> &str {
            "stub"
        }
    }

    const SPEC: &str = "---\ndescription: Reviews pull requests\n---\n\nYou are a reviewer.\n";

    fn workspace(tag: &str) -> (std::path::PathBuf, Arc<dyn Filesystem>) {
        let dir = std::env::temp_dir().join(format!("asr_agengen_{tag}_{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        let fs: Arc<dyn Filesystem> = Arc::new(LocalFilesystem::new(&dir));
        (dir, fs)
    }

    async fn call_tool(tool: &AgentGenerateTool) {
        let args = serde_json::json!({"name": "code-reviewer", "description": "review PRs"});
        tool.call(args.as_object().unwrap().clone(), Default::default())
            .await
            .expect("tool call");
    }

    fn written_spec(dir: &std::path::Path) -> String {
        std::fs::read_to_string(dir.join("subagents/code-reviewer.md")).unwrap()
    }

    #[tokio::test]
    async fn model_generation_writes_a_parseable_spec() {
        let (dir, fs) = workspace("model");
        let tool = AgentGenerateTool::new(fs)
            .with_model(Arc::new(StubModel { text: SPEC.into() }) as Arc<dyn Model>);
        call_tool(&tool).await;

        let content = written_spec(&dir);
        let declaration = crate::agent::subagent::parse(&content, "code-reviewer", None)
            .expect("generated spec is parseable");
        assert_eq!(declaration.description, "Reviews pull requests");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[tokio::test]
    async fn a_malformed_generation_falls_back_to_the_template() {
        let (dir, fs) = workspace("fallback");
        let tool = AgentGenerateTool::new(fs).with_model(Arc::new(StubModel {
            text: "not markdown".into(),
        }) as Arc<dyn Model>);
        call_tool(&tool).await;

        let content = written_spec(&dir);
        assert!(content.contains("a focused subagent"), "{content}");
        assert!(crate::agent::subagent::parse(&content, "code-reviewer", None).is_some());
        let _ = std::fs::remove_dir_all(&dir);
    }
}
